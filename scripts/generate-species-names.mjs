/**
 * Writes supabase/functions/_shared/species-names.ts: every plant the app
 * knows, by scientific and common name, for the care function to resolve
 * "snake plant" to Dracaena trifasciata before it pays for a guide.
 *
 * Generated rather than imported because the function is deployed on its own
 * and can't reach src/. care-library.test.mjs fails if the copy goes stale;
 * `npm run plants` rewrites it.
 *
 * Usage: node scripts/generate-species-names.mjs
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { SPECIES, scientificName } from "../src/domain/species.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = join(ROOT, "supabase", "functions", "_shared", "species-names.ts");

export function speciesNamesSource() {
  const rows = SPECIES.map((s) => `  ${JSON.stringify({ sci: scientificName(s), common: s.common })},`);
  return `// Generated by scripts/generate-species-names.mjs from src/domain/species.ts -- don't edit.
import type { SpeciesName } from "./care-names.ts";

export const SPECIES_NAMES: SpeciesName[] = [
${rows.join("\n")}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, speciesNamesSource());
  console.log(`Wrote ${SPECIES.length} species to ${OUT.slice(ROOT.length + 1)}`);
}
