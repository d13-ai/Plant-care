/**
 * The plant library as the app's care guides.
 *
 * The care function files one guide per species in care_cards and only asks
 * the model when a species isn't there. The library already has hand-written,
 * ASPCA-checked care for every plant page on the site, so those species go
 * into care_cards from here instead: no model, no cost, and the app says what
 * the website says. Model-written guides stay for everything the library
 * doesn't cover.
 *
 * Each guide is filed with model "library", which is how the app knows to say
 * "From the PlantParlour plant library" rather than "Written by AI".
 *
 * Usage: node scripts/care-library.mjs   (part of `npm run plants`)
 *   writes public/care-library.json, which ships with the site. Once it is
 *   live on plantparlour.org, scripts/care-library-load.sql reads it into
 *   care_cards. That upserts, so it is safe to run again after the library
 *   changes; it replaces model-written guides for the same species.
 *
 *   node scripts/care-library.mjs --sql prints the same as one INSERT, for
 *   loading a database that can't reach the site.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { everyDays, plantPages } from "./generate-plant-pages.mjs";
import { PLANTS } from "./plants-data.mjs";
import { TEMPERATURE } from "./temperature-data.mjs";
import { careKey } from "../supabase/functions/_shared/care-names.ts";

const DIFFICULTY = {
  Easy: "easy",
  "Easy-going": "easy",
  Straightforward: "easy",
  "Needs attention": "moderate",
  Fussy: "fussy",
};

/** Ends with a full stop, once. */
const sentence = (s) => {
  const t = String(s).trim();
  return /[.!?]$/.test(t) ? t : `${t}.`;
};

/** The blurb's opening, as the guide's one-line summary: two sentences if they're short enough, else one. */
function summaryOf(blurb) {
  const parts = blurb.trim().split(/(?<=[.!?])\s+/);
  const two = parts.slice(0, 2).join(" ");
  return two.length <= 320 ? two : parts[0];
}

/** One plant page as a care card, in the shape the care function returns. */
export function libraryCard(page) {
  const difficulty = DIFFICULTY[page.difficulty];
  if (!difficulty) throw new Error(`${page.sci}: no difficulty mapping for "${page.difficulty}"`);
  const temperature = TEMPERATURE[page.entry.genus];
  if (!temperature) throw new Error(`${page.sci}: no temperature for genus ${page.entry.genus}`);

  // The species' own problems first -- they're the specific ones -- then the genus's.
  const own = PLANTS[page.slug]?.problems?.length ?? 0;
  const problems = [...page.problems.slice(page.problems.length - own), ...page.problems.slice(0, page.problems.length - own)];

  return {
    summary: summaryOf(page.blurb),
    difficulty,
    light: sentence(page.lightLong),
    water: `${sentence(page.waterHow)} As a starting point, water ${everyDays(page.entry.waterEveryDays)}.`,
    humidity: sentence(page.humidity),
    temperature,
    soil: sentence(page.soilLong),
    feeding: sentence(page.feed),
    repotting: sentence(page.repotNote),
    common_problems: problems.slice(0, 5).map(([problem, cause, fix]) => ({ problem, fix: `${sentence(cause)} ${sentence(fix)}` })),
    toxicity: sentence(page.toxicity),
    source: "library",
    url: page.url,
  };
}

/** Every page in the library, keyed the way the care function looks them up. */
export function libraryCards() {
  return plantPages().map((page) => ({ key: careKey(page.sci), species: page.sci, card: libraryCard(page) }));
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function librarySql(rows = libraryCards()) {
  const values = rows.map((r) => `  (${lit(r.key)}, ${lit(r.species)}, ${lit(JSON.stringify(r.card))}::jsonb, 'library')`);
  return `-- Generated by scripts/care-library.mjs: ${rows.length} care guides from the plant library.
insert into public.care_cards (species_key, species, card, model) values
${values.join(",\n")}
on conflict (species_key) do update set species = excluded.species, card = excluded.card, model = excluded.model;
`;
}

export const JSON_OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "public", "care-library.json");

/** What the site serves: [{ key, species, card }], in page order. */
export const libraryJson = (rows = libraryCards()) => `${JSON.stringify(rows)}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--sql")) process.stdout.write(librarySql());
  else {
    const rows = libraryCards();
    writeFileSync(JSON_OUT, libraryJson(rows));
    console.log(`Wrote ${rows.length} care guides to public/care-library.json`);
  }
}
